import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

export async function loadDeveloperContracts(){
  const [sdkText,errorText]=await Promise.all([
    readFile('docs/api/PUBLIC-SDK.v0.1.json','utf8'),
    readFile('docs/api/ERROR-CATALOG.v0.1.json','utf8')
  ]);
  return {
    sdk:JSON.parse(sdkText),
    errors:JSON.parse(errorText)
  };
}

function mdCell(value){
  return String(value??'').replaceAll('|','\\|').replaceAll('\n',' ');
}

export function renderApiReference(sdk){
  const lines=[
    '# OpenContainer Public SDK Reference',
    '',
    '> Generated from docs/api/PUBLIC-SDK.v0.1.json. Do not edit this file by hand.',
    '',
    'Package: '+sdk.package,
    'Contract version: '+sdk.version,
    '',
    '## Package exports',
    '',
    '| Subpath | Target |',
    '| --- | --- |'
  ];
  for(const [subpath,target] of Object.entries(sdk.exportMap??{}))lines.push('| '+mdCell(subpath)+' | '+mdCell(target)+' |');
  lines.push('','## Root module exports','');
  for(const name of sdk.rootExports??[])lines.push('- '+name);

  const memberTable=(title,members)=>{
    lines.push('',title,'','| Member | Kind | Signature |','| --- | --- | --- |');
    for(const member of members??[])lines.push('| '+mdCell(member.name)+' | '+mdCell(member.kind)+' | '+mdCell(member.signature)+' |');
  };
  memberTable('## Static members',sdk.staticMembers);
  memberTable('## Instance members',sdk.instanceMembers);

  lines.push('','## Advanced runtime facets','');
  lines.push('These facets are intentionally reachable from an OpenContainer instance. They are advanced runtime surfaces, not independent package-subpath contracts.');
  lines.push('');
  for(const name of sdk.advancedRuntimeFacets??[])lines.push('- runtime.'+name);

  lines.push('','## Privacy boundary','',sdk.privacyBoundary?.statement??'');
  lines.push('','The following package subpaths are explicitly not public:','');
  for(const subpath of sdk.privacyBoundary?.noPublicPackageSubpaths??[])lines.push('- '+subpath);
  lines.push('');
  return lines.join('\n');
}

export function renderErrorReference(catalog){
  const lines=[
    '# OpenContainer Error Reference',
    '',
    '> Generated from docs/api/ERROR-CATALOG.v0.1.json. Do not edit this file by hand.',
    '',
    'Errors are stable machine codes. Consumer UI may translate the prose, but branching/recovery logic should use error.code.',
    '',
    '| Code | Compatibility class | Cause | Consequence | Recovery |',
    '| --- | --- | --- | --- | --- |'
  ];
  for(const error of catalog.errors??[]){
    lines.push('| '+mdCell(error.code)+' | '+mdCell(error.compatibilityClass)+' | '+mdCell(error.cause)+' | '+mdCell(error.consequence)+' | '+mdCell(error.recovery)+' |');
  }
  lines.push('');
  return lines.join('\n');
}

export async function generateDeveloperDocs({write=false}={}){
  const {sdk,errors}=await loadDeveloperContracts();
  const outputs={
    'docs/api/API-REFERENCE.md':renderApiReference(sdk),
    'docs/api/ERROR-REFERENCE.md':renderErrorReference(errors)
  };
  const drift=[];
  for(const [path,expected] of Object.entries(outputs)){
    if(write){
      await writeFile(resolve(path),expected);
      continue;
    }
    let actual=null;
    try{actual=await readFile(resolve(path),'utf8');}catch{}
    if(actual!==expected)drift.push(path);
  }
  return Object.freeze({
    schema:'opencontainer.developer-docs-generation.v0.1',
    ok:drift.length===0,
    drift:Object.freeze(drift),
    outputs:Object.freeze(Object.keys(outputs))
  });
}

if(import.meta.url===new URL('file://'+process.argv[1]).href){
  const write=process.argv.includes('--write');
  const receipt=await generateDeveloperDocs({write});
  console.log(JSON.stringify(receipt,null,2));
  if(!write&&!receipt.ok)process.exitCode=1;
}
